const STORAGE_KEY = 'submovie-preferred-language-v1';
const allowed = value => value === 'ja' || value === 'en';
export function browserLanguage(value = globalThis.navigator?.language) {
  return /^ja(?:-|$)/i.test(String(value || '')) ? 'ja' : 'en';
}
function savedLanguage() { try { const value = globalThis.localStorage?.getItem(STORAGE_KEY); return allowed(value) ? value : null; } catch { return null; } }
export const language = savedLanguage() || browserLanguage();
export const locale = language === 'ja' ? 'ja-JP' : 'en-US';
const normalize = text => text.trim().replace(/\s+/g, ' ');
export function t(key, ...values) {
  if (typeof key !== 'string') return String(key ?? '');
  const copy = language === 'en' ? (Object.hasOwn(EN, key) ? EN[key] : Object.hasOwn(EN, normalize(key)) ? EN[normalize(key)] : key) : key;
  return copy.replace(/\{(\d+)\}/g, (match, i) => Number(i) < values.length ? String(values[Number(i)] ?? '') : match);
}
// For translations interpolated into existing HTML templates, never insert markup.
export function th(key, ...values) { return t(key, ...values).replace(/[&<>"']/g, char => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[char])); }
export function compactCount(value) {
  const n = Number(value), count = Number.isFinite(n) ? Math.max(0, Math.floor(n)) : 0;
  return language === 'en' ? new Intl.NumberFormat(locale, {notation:'compact', maximumFractionDigits:1}).format(count)
    : count >= 100000000 ? `${Math.floor(count/10000000)/10}億` : count >= 10000 ? `${Math.floor(count/1000)/10}万` : count.toLocaleString(locale);
}
const attributes = ['aria-label', 'aria-valuetext', 'title', 'placeholder', 'alt'];
const selector = ['[data-ui-copy]', ...attributes.map(name=>'[data-ui-'+name+']')].join(',');
function localizeStatic(root) {
  const nodes = [...(root.matches?.(selector) ? [root] : []), ...root.querySelectorAll(selector)];
  for (const node of nodes) {
    if (node.hasAttribute('data-ui-copy')) node.textContent = t(node.getAttribute('data-ui-copy'));
    for (const name of attributes) if (node.hasAttribute('data-ui-'+name)) node.setAttribute(name, t(node.getAttribute('data-ui-'+name)));
  }
}
function startStatic() {
  document.documentElement.lang = language;
  localizeStatic(document);
  // Only explicitly marked, author-written UI labels are translated.
  new MutationObserver(records => {
    for (const record of records) {
      if (record.type === 'attributes') localizeStatic(record.target);
      else for (const node of record.addedNodes) if (node.nodeType === 1) localizeStatic(node);
    }
  }).observe(document.body, {childList:true, subtree:true, attributes:true, attributeFilter:attributes.map(name=>'data-ui-'+name).concat('data-ui-copy')});
}
